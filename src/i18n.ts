export function getLocale(): string {
	const lang = vscode.env.language;
	if (lang.startsWith('es')) { return 'es'; }
	return 'en';
}

export function t(key: string): string {
	const locale = getLocale();
	return i18n[locale][key] ?? i18n['en'][key] ?? key;
}
